def all_specs() -> tuple[SettingSpec, ...]:
    return SETTING_SPECS


def specs_by_id() -> dict[str, SettingSpec]:
    return {s.id: s for s in SETTING_SPECS}


def specs_for_group(group: str) -> tuple[SettingSpec, ...]:
    return tuple(s for s in SETTING_SPECS if s.group == group)


def validate_registry() -> list[str]:
    """Return registry integrity problems (empty = ok)."""
    problems: list[str] = []
    seen: set[str] = set()
    for spec in SETTING_SPECS:
        if spec.id in seen:
            problems.append(f"duplicate id: {spec.id}")
        seen.add(spec.id)
        if not spec.file_rel:
            problems.append(f"{spec.id}: empty file_rel")
        low = spec.file_rel.casefold()
        if "serialport" in low and (
            low.endswith("layout.json") or low.endswith("locations.json")
        ):
            problems.append(f"{spec.id}: forbidden serialport map")
        if "/licen" in f"/{low}/" or low.endswith("licence.dll"):
            problems.append(f"{spec.id}: forbidden licence path")
        if spec.kind not in (
            "scalar",
            "bool",
            "int_list",
            "str_list",
            "token_map",
            "button_map",
            "ini_scalar",
            "service_enabled",
        ):
            problems.append(f"{spec.id}: bad kind {spec.kind!r}")
        if spec.per_theme and "*" not in spec.file_rel:
            problems.append(f"{spec.id}: per_theme but file_rel has no *")
    return problems
