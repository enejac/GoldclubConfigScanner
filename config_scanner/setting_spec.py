"""Declarative registry of GoldClub / GameStar settings for jurisdiction profiling.

One ``SettingSpec`` per setting so the probe, miner, and wizard share one map.
XML walking reuses the namespace-agnostic helpers in ``slot_setup``.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Literal

SettingKind = Literal[
    "scalar",
    "bool",
    "int_list",
    "str_list",
    "token_map",
    "button_map",
    "ini_scalar",
    "service_enabled",
]


@dataclass(frozen=True)
class SettingSpec:
    """One configurable setting that can be probed against a Goldclub-shaped tree."""

    id: str
    label: str
    group: str
    file_rel: str
    locator: str
    kind: SettingKind
    cs_pack_delivers: bool
    per_theme: bool = False
    notes: str = ""


# Groups used by the wizard matrix (display order).
SETTING_GROUPS: tuple[str, ...] = (
    "Jurisdiction",
    "Denomination",
    "UI",
    "Math",
    "SAS",
    "Ticketing",
    "Bill acceptor",
    "Hardware",
    "Dallas",
    "Identity",
    "Aurum",
    "Audio",
    "Buttons",
)


def _spec(
    setting_id: str,
    label: str,
    group: str,
    file_rel: str,
    locator: str,
    kind: SettingKind,
    *,
    cs_pack_delivers: bool = True,
    per_theme: bool = False,
    notes: str = "",
) -> SettingSpec:
    return SettingSpec(
        id=setting_id,
        label=label,
        group=group,
        file_rel=file_rel.replace("\\", "/"),
        locator=locator,
        kind=kind,
        cs_pack_delivers=cs_pack_delivers,
        per_theme=per_theme,
        notes=notes,
    )


